export type TranslationKey = keyof (typeof translations)['en'];
export type TranslationVars = Record<string, string | number>;

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'ru';
}

export function getStoredLocale(): Locale {
  if (typeof window !== 'undefined') {
    try {
      const settingsRaw = window.localStorage.getItem('promptlab:settings:v1');
      if (settingsRaw) {
        const settings = JSON.parse(settingsRaw) as { locale?: unknown };
        if (isLocale(settings.locale)) return settings.locale;
      }
      const stored = window.localStorage.getItem(localeStorageKey);
      if (isLocale(stored)) return stored;
    } catch {
      // Language detection still works when browser storage is unavailable.
    }
  }

  const browserLanguage = typeof navigator === 'undefined' ? '' : navigator.language;
  return browserLanguage.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

