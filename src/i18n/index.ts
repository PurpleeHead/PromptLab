export function translate(key: TranslationKey, locale: Locale, values: TranslationVars = {}): string {
  const source = translations[locale][key] ?? translations.en[key] ?? String(key);
  return source.replace(/\{(\w+)\}/g, (_match: string, token: string) => {
    const value = values[token];
    return value === undefined ? `{${token}}` : String(value);
  });
}

