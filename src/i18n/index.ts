export function translateText(text: string, locale: Locale): string {
  const exact = Object.entries(translations.en).find(([, value]) => value === text);
  if (exact) return translate(exact[0] as TranslationKey, locale);
  const caseInsensitive = Object.entries(translations.en).find(([, value]) => value.toLocaleLowerCase() === text.toLocaleLowerCase());
  if (caseInsensitive) return translate(caseInsensitive[0] as TranslationKey, locale);
  if (locale === 'ru' && inlineRussianTranslations[text.trim()]) return inlineRussianTranslations[text.trim()];
  if (locale === 'ru') {
    const imported = /^(\d+) prompts? imported\.$/.exec(text.trim());
    if (imported) {
      const count = Number(imported[1]);
      const noun = count % 100 >= 11 && count % 100 <= 14 ? 'промптов' : count % 10 === 1 ? 'промпт' : count % 10 >= 2 && count % 10 <= 4 ? 'промпта' : 'промптов';
      return `Импортировано ${count} ${noun}.`;
    }
    const restored = /^Version (\d+) loaded\. Save to make it current\.$/.exec(text.trim());
    if (restored) return `Версия ${restored[1]} загружена. Сохраните её, чтобы сделать текущей.`;
    const categories = /^(\d+) active categories$/.exec(text.trim());
    if (categories) return `${categories[1]} активных категорий`;
    const collectionCount = /^(\d+) prompts in this collection$/.exec(text.trim());
    if (collectionCount) {
      const count = Number(collectionCount[1]);
      const noun = count % 100 >= 11 && count % 100 <= 14 ? 'промптов' : count % 10 === 1 ? 'промпт' : count % 10 >= 2 && count % 10 <= 4 ? 'промпта' : 'промптов';
      return `${count} ${noun} в этой коллекции`;
    }
    const saved = /^Saved (.+)$/.exec(text.trim());
    if (saved) return `Сохранено: ${saved[1]}`;
  }

  for (const [key, template] of Object.entries(translations.en)) {
    if (/^\{\w+\}$/.test(template)) continue;
    const tokens = [...template.matchAll(/\{(\w+)\}/g)];
    if (!tokens.length) continue;

    const pattern = template
      .split(/\{(\w+)\}/g)
      .map((part, index) => index % 2 === 1 ? '(.+?)' : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
      .join('');
    const match = new RegExp(`^${pattern}$`).exec(text.trim());
    if (!match) continue;

    const values = Object.fromEntries(tokens.map(([placeholder], index) => [placeholder.slice(1, -1), match[index + 1]]));
    return translate(key as TranslationKey, locale, values);
  }

  return text;
}

const LocaleContext = createContext<Locale>('en');

export function LocaleProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return createElement(LocaleContext.Provider, { value: locale }, children);
}

export function formatRelativeDate(date: string, locale: Locale): string {
  const target = new Date(date).getTime();
  const diffDays = Math.floor((target - Date.now()) / 86400000);
  if (Math.abs(diffDays) === 0) {
    return locale === 'ru' ? 'Сегодня' : 'Today';
  }
  const formatter = new Intl.RelativeTimeFormat(locale, { numeric: 'auto' });
  if (Math.abs(diffDays) < 7) {
    return formatter.format(diffDays, 'day');
  }
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric' }).format(new Date(date));
}

export function useTranslation(explicitLocale?: Locale) {
  const contextLocale = useContext(LocaleContext);
  const locale = explicitLocale ?? contextLocale;
  return {
    locale,
    t: (key: TranslationKey, values?: TranslationVars) => translate(key, locale, values),
    tText: (text: string) => translateText(text, locale),
    formatNumber: (value: number) => new Intl.NumberFormat(locale).format(value),
    formatDate: (value: string) => new Intl.DateTimeFormat(locale, { dateStyle: 'medium' }).format(new Date(value)),
  };
}


export function pluralizeCount(
  count: number,
  locale: Locale,
  englishSingular: string,
  englishPlural: string,
  russianForms: readonly [string, string, string],
): string {
  if (locale !== 'ru') return count === 1 ? englishSingular : englishPlural;
  const absolute = Math.abs(count);
  const lastTwo = absolute % 100;
  const last = absolute % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return russianForms[2];
  if (last === 1) return russianForms[0];
  if (last >= 2 && last <= 4) return russianForms[1];
  return russianForms[2];
}
